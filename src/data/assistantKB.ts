export function answerQuestion(segment: Segment, question: string): string {
  const q = question.toLowerCase();
  const rules = KB[segment];
  const scored = rules
    .map((r) => ({ r, score: r.keywords.filter((k) => q.includes(k)).length }))
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score);
  if (scored.length > 0) return scored[0].r.answer;
  return 'Уточните вопрос детальнее — назовите параметр (помол, доза, температура, время) или симптом (вкус, пена, скорость пролива). Ассистент отвечает по базе ТТК 202f и SCA-стандартов.';
}
